namespace Application.Features.Definition.Context
{
    /// <summary>
    /// قفل سریال‌سازی عملیات دیتابیس در محدوده یک درخواست (DI Scope).
    ///
    /// چرا این کار به‌جای یک قفل استاتیک سراسری؟
    /// نسخه قبلی یک <c>static SemaphoreSlim(1,1)</c> در کل پروسه بود. آن قفل در
    /// برنامه دسکتاپ تک‌کاربره قابل قبول بود، اما در وب باعث می‌شد همه درخواست‌های
    /// موازی پشت یک قفل واحد صف بکشند و با افزایش کاربران سیستم قفل می‌شد.
    ///
    /// این سرویس به صورت Scoped ثبت می‌شود، بنابراین:
    /// هر درخواست وب قفل مستقل خود را دارد (بدون گلوگاه)،
    /// و در عین حال استفاده همزمان از یک نمونه DbContext در همان درخواست سریال می‌شود
    /// (که خطای «second operation started on this context» را ایجاد می‌کرد).
    ///
    /// توجه: این قفل فقط داخل یک پروسه کار می‌کند. برای هماهنگی بین چند سرور یا بین
    /// نسخه وب و نسخه دسکتاپ، منطق موجودی باید به تراکنش دیتابیسی متکی باشد
    /// (مانند <c>ApproveReceiptAsync</c> و <c>ApproveIssueAsync</c>).
    /// </summary>
    public interface IDbLock
    {
        /// <summary>
        /// سمافور مربوط به همین scope. استفاده به شکل <c>await DbLock.Semaphore.WaitAsync()</c>
        /// و آزادسازی در بلوک <c>finally</c> انجام می‌شود.
        /// </summary>
        SemaphoreSlim Semaphore { get; }
    }
}
